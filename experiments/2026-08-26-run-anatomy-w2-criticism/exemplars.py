#!/usr/bin/env python3
"""Render EXEMPLARS.md — every quotation pulled verbatim from the record.

RESULTS.md's claims are counts; this file is what the counts are counts OF.
Nothing here is paraphrased and nothing is selected by how it reads: each
section states the mechanical predicate that chose its rows, then prints the
first rows that satisfy it.

Usage:  python exemplars.py > EXEMPLARS.md
"""
from __future__ import annotations

import json
import pathlib
import sys
import textwrap

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "src"))

from deepreason import programs  # noqa: E402
from deepreason.harness import Harness  # noqa: E402

ROOTS = {
    "P-R1": REPO / "experiments/2026-08-25-poietics-program/run",
    "P-C1": REPO / "experiments/2026-08-25-change-constructive-frontier/run",
}
CENSUS = {"P-R1": "pr1_census.json", "P-C1": "pc1_census.json"}


def body(label: str) -> dict[str, str]:
    h = Harness(ROOTS[label], read_only=True)
    out = {}
    for aid, art in h.state.artifacts.items():
        try:
            out[aid] = programs.content_text(art, h.blobs)
        except Exception:  # noqa: BLE001
            out[aid] = ""
    return out


def quote(text: str, limit: int = 1400) -> str:
    t = (text or "").strip()
    if len(t) > limit:
        t = t[:limit] + " […truncated for this file; the record holds it whole]"
    return "\n".join("> " + line for line in textwrap.wrap(t, 88) or [""])


bodies = {k: body(k) for k in ROOTS}
cen = {k: json.loads((HERE / v).read_text()) for k, v in CENSUS.items()}

print("# W2 criticism anatomy — exemplars, quoted verbatim\n")
print("Generated by `exemplars.py`. Selection is by a stated mechanical")
print("predicate, never by how a passage reads.\n")

print("## E1. What a status-moving criticism actually says\n")
print("Predicate: the first `Crit` event in each root that carried a warrant;")
print("its criticism artifact printed whole.\n")
for label in ROOTS:
    m = cen[label]["mechanical"][0]
    print(f"**{label}**, log seq {m['seq']}, commitment `{m['commitment']}`, "
          f"target `{m['target'][:12]}` (final status **{m['target_status']}**):\n")
    print(quote(bodies[label].get(m["crit_artifact"], "")))
    print(f"\nThe commitment it enforced, verbatim from `problem.json`:\n")
    ev = next((c["eval"] for c in cen[label]["problem_criteria"]
               if c["id"] == m["commitment"]), m.get("eval"))
    print("```\n" + str(ev) + "\n```\n")

print("## E2. What a criticism that moved nothing says\n")
print("Predicate: the LONGEST LLM attack in each root, by case length. Every")
print("one of these was recorded, and none was shown to a conjecture dispatch.\n")
for label in ROOTS:
    at = [d for d in cen[label]["dispatches"] if d["outcome"] == "attack"]
    d = max(at, key=lambda x: x.get("case_len") or 0)
    print(f"**{label}**, target `{(d['target'] or '')[:12]}` (final status "
          f"**{d['target_status']}**), {d['case_len']} characters, dispatch "
          f"authority `{d['dispatch_authority']}`, warrants carried: "
          f"{len(d['warrants_carried'])}:\n")
    print(quote(d["case_text"], 2000))
    print()

print("## E3. A misquotation, to one letter\n")
print("Predicate: quoted spans whose punctuation-trimmed, elision-tolerant form")
print("is absent from every item the dispatch was shown.\n")
for label in ROOTS:
    at = [d for d in cen[label]["dispatches"] if d["outcome"] == "attack"]
    shown = 0
    for d in at:
        for q in d.get("quotes_of_target", []):
            if q["trimmed_in_target"] or q["trimmed_in_any_exposed"] or q["trimmed_in_problem"]:
                continue
            tgt = bodies[label].get(d["target"] or "", "")
            head = q["quote"][:24]
            i = tgt.find(head[:12])
            near = tgt[max(0, i - 40):i + 160] if i >= 0 else "(no nearby text)"
            print(f"**{label}** — the critic wrote:\n")
            print(quote(q["quote"], 300))
            print(f"\nThe target `{(d['target'] or '')[:12]}` says:\n")
            print(quote(near, 300))
            print()
            shown += 1
            break
        if shown >= 2:
            break

print("## E4. An evidence citation naming nothing\n")
print("Predicate: `premise_evidence.block` that resolves to no dossier block.\n")
for label in ROOTS:
    at = [d for d in cen[label]["dispatches"] if d["outcome"] == "attack"]
    shown = 0
    for d in at:
        for e in d.get("evidence_citations", []):
            if e["in_dossier"] or not e["quote"].strip():
                continue
            where = ("verbatim in the target it was shown"
                     if e.get("quote_verbatim_in_target")
                     else "verbatim in the problem statement"
                     if e.get("quote_verbatim_in_problem")
                     else "in nothing this dispatch was shown")
            print(f"**{label}** — cited block `{e['cited']}` "
                  f"(dossier blocks in this root: "
                  f"{cen[label]['n_dossier_blocks']}); the quote is {where}:\n")
            print(quote(e["quote"], 400))
            print()
            shown += 1
            break
        if shown >= 2:
            break

print("## E5. A critic declining to attack\n")
print("Predicate: the first dispatch whose reply set `attack: false`.\n")
for label in ROOTS:
    d = next((x for x in cen[label]["dispatches"] if x["outcome"] == "declined"), None)
    if d is None:
        continue
    print(f"**{label}** — target `{(d['target'] or '')[:12]}` "
          f"(final status **{d['target_status']}**), {d['completion_tokens']} "
          f"completion tokens spent to say nothing was wrong. The target:\n")
    print(quote(bodies[label].get(d["target"] or "", ""), 900))
    print()

print("## E6. P-C1: the one candidate that ever improved the score\n")
q = json.loads((HERE / "pc1_q5.json").read_text())
best = q["best_score_trajectory"][-1]
print(f"Predicate: the last entry in the best-score trajectory — log seq "
      f"{best['seq']}, exact score {best['new_best']}, with "
      f"{best['criticisms_before']} criticism events already on the record and "
      f"{q['n_criticism_events_total'] - best['criticisms_before']} still to come.\n")
print(quote(bodies["P-C1"].get(best["artifact"], ""), 1200))
