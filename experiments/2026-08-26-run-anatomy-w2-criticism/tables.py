#!/usr/bin/env python3
"""Render TABLES.md from the census/q5/sweep JSONs.

Every number RESULTS.md quotes is generated here, never typed by hand.
Re-running this after re-running census.py/q5.py/sweep.py regenerates the
tables; if a number in RESULTS.md cannot be found in TABLES.md, it is not
this tranche's number.

Usage:  python tables.py > TABLES.md
"""
from __future__ import annotations

import collections
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOTS = [("P-R1", "pr1"), ("P-C1 ARM H", "pc1")]


def load(name: str) -> dict:
    return json.loads((HERE / name).read_text())


def pct(n, d):
    return "—" if not d else f"{n}/{d} ({100.0 * n / d:.0f}%)"


def rate(x):
    return "—" if x is None else f"{100.0 * x:.1f}%"


print("# W2 criticism anatomy — the tables\n")
print("Generated by `tables.py` from `pr1_census.json`, `pc1_census.json`,")
print("`pr1_q5.json`, `pc1_q5.json`, `sweep.json`. Do not hand-edit.\n")

# ---------------------------------------------------------------- inventory
print("## 0. What was censused\n")
print("| Root | Crit events | Artifacts | Warrants | att edges | accepted | refuted |")
print("|---|---|---|---|---|---|---|")
for label, key in ROOTS:
    c = load(f"{key}_census.json")
    s = c["status_counts"]
    print(f"| {label} | {c['rules'].get('Crit', 0)} | {c['n_artifacts']} | "
          f"{c['n_warrants']} | {c['n_att_edges']} | {s.get('accepted', 0)} | "
          f"{s.get('refuted', 0)} |")
print()

# ------------------------------------------------------------- 1. TARGETS
print("## 1. TARGETS — what each criticism attacked\n")
print("Two populations, and they are not comparable: a MECHANICAL criticism is a")
print("commitment verdict the harness computed; an LLM ATTACK is prose a critic")
print("seat wrote. Both are `Crit` events on the log.\n")
print("| Root | Criticism dispatches | attack | declined | no case | unparsed reply |")
print("|---|---|---|---|---|---|")
for label, key in ROOTS:
    c = load(f"{key}_census.json")
    o = collections.Counter(d["outcome"] for d in c["dispatches"])
    print(f"| {label} | {sum(o.values())} | {o['attack']} | {o['declined']} | "
          f"{o['no_case']} | {o['unparsed_reply']} |")
print()
print("### 1a. LLM attacks, by what the attack contained\n")
print("The columns are the criticism wire contract's OWN fields, not this")
print("census's reading of the prose.\n")
print("| Root | attacks | names a premise | offers a counterexample | "
      "cites evidence | quotes the target verbatim | none of these |")
print("|---|---|---|---|---|---|---|")
for label, key in ROOTS:
    c = load(f"{key}_census.json")
    at = [d for d in c["dispatches"] if d["outcome"] == "attack"]
    n = len(at)
    prem = sum(1 for d in at if d.get("has_premise"))
    cex = sum(1 for d in at if d.get("has_counterexample"))
    ev = sum(1 for d in at if d.get("evidence_citations"))
    qv = sum(1 for d in at
             if any(q.get("trimmed_in_target") for q in d.get("quotes_of_target", [])))
    none = sum(1 for d in at
               if not d.get("has_premise") and not d.get("has_counterexample")
               and not d.get("evidence_citations")
               and not any(q.get("trimmed_in_target")
                           for q in d.get("quotes_of_target", [])))
    print(f"| {label} | {n} | {pct(prem, n)} | {pct(cex, n)} | {pct(ev, n)} | "
          f"{pct(qv, n)} | {pct(none, n)} |")
print()
print("### 1b. Mechanical criticism, by the commitment it attacked\n")
print("| Root | Mechanical criticisms | Commitments used | Are they the problem's own criteria? |")
print("|---|---|---|---|")
for label, key in ROOTS:
    c = load(f"{key}_census.json")
    used = collections.Counter(m.get("commitment") for m in c["mechanical"])
    crit_ids = {x["id"] for x in c["problem_criteria"]}
    from_criteria = sum(v for k, v in used.items() if k in crit_ids)
    detail = "; ".join(f"`{k}` ×{v}" for k, v in used.most_common())
    print(f"| {label} | {len(c['mechanical'])} | {detail} | "
          f"{pct(from_criteria, len(c['mechanical']))} |")
print()

# ------------------------------------------- 2. COMMITMENT ATTACK CORRECTNESS
print("## 2. COMMITMENT ATTACKS — correctness judged mechanically\n")
print("Every warrant's verdict RE-DERIVED by `deepreason.programs.evaluate` on")
print("the target's own bytes. `correct` = the re-derived verdict equals the")
print("verdict the warrant stored.\n")
print("| Root | correct | misquoted | attacked-nonexistent | unverifiable | "
      "commitment present in the target's interface |")
print("|---|---|---|---|---|---|")
for label, key in ROOTS:
    c = load(f"{key}_census.json")
    r = collections.Counter(m["row"] for m in c["mechanical"])
    iface = sum(1 for m in c["mechanical"] if m.get("in_target_interface"))
    tot = len(c["mechanical"])
    print(f"| {label} | {pct(r['correct'], tot)} | {r['misquoted']} | "
          f"{r['attacked-nonexistent']} | {r['unverifiable']} | {pct(iface, tot)} |")
print()
print("### 2a. LLM attacks — the same four rows, on what an LLM attack can be checked for\n")
print("An LLM attack names no commitment, so it cannot be scored on the rows")
print("above. What CAN be checked mechanically is whether the thing it quoted")
print("is in the artifact it was shown. A span is matched whitespace- and")
print("edge-punctuation-insensitively, and an elided `A ... B` quotation counts")
print("as accurate when A and B both occur in order.\n")
print("| Root | quoted spans | verbatim in the target | in another item the "
      "dispatch was shown | in the problem statement | in NOTHING it was shown |")
print("|---|---|---|---|---|---|")
for label, key in ROOTS:
    c = load(f"{key}_census.json")
    qs = [q for d in c["dispatches"] if d["outcome"] == "attack"
          for q in d.get("quotes_of_target", [])]
    n = len(qs)
    t = sum(1 for q in qs if q.get("trimmed_in_target"))
    o = sum(1 for q in qs if not q.get("trimmed_in_target")
            and q.get("trimmed_in_any_exposed"))
    p = sum(1 for q in qs if not q.get("trimmed_in_target")
            and not q.get("trimmed_in_any_exposed") and q.get("trimmed_in_problem"))
    print(f"| {label} | {n} | {pct(t, n)} | {pct(o, n)} | {pct(p, n)} | "
          f"{pct(n - t - o - p, n)} |")
print()
print("### 2b. Evidence citations — a block that exists, and one the critic was shown\n")
print("| Root | citations | names a real dossier block | that block was shown "
      "to THIS dispatch | quote verbatim in the cited block | quote verbatim in the target instead |")
print("|---|---|---|---|---|---|")
for label, key in ROOTS:
    c = load(f"{key}_census.json")
    ec = [e for d in c["dispatches"] if d["outcome"] == "attack"
          for e in d.get("evidence_citations", [])]
    n = len(ec)
    real = sum(1 for e in ec if e.get("in_dossier"))
    shown = sum(1 for e in ec if e.get("was_exposed_to_this_dispatch"))
    vq = sum(1 for e in ec if e.get("quote_verbatim_in_cited_block"))
    vt = sum(1 for e in ec if e.get("quote_verbatim_in_target"))
    print(f"| {label} | {n} | {pct(real, n)} | {pct(shown, n)} | {pct(vq, n)} | "
          f"{pct(vt, n)} |")
print()

# --------------------------------------------------------- 3. CAUSAL WORK
print("### 2c. The harness's OWN citation checks (Measures on the log)\n")
print("`evidence-citation:` codes check a CANDIDATE's `evidence_refs`;")
print("`premise-citation:` codes check a CRITIC's `premise_evidence`. Two")
print("channels, two call sites, and — as the last column shows — two very")
print("different rates of ever being checked at all.\n")
print("| Root | candidate-citation checks | critic-citation checks | "
      "critic evidence citations EMITTED | emitted but never checked |")
print("|---|---|---|---|---|")
for label, key in ROOTS:
    c = load(f"{key}_census.json")
    ch = c["citation_checks"]
    cand = sum(v for k, v in ch.items() if k.startswith("evidence-citation"))
    crit = sum(v for k, v in ch.items() if k.startswith("premise-citation"))
    emitted = sum(len(d.get("evidence_citations", []))
                  for d in c["dispatches"] if d["outcome"] == "attack")
    print(f"| {label} | {cand} | {crit} | {emitted} | "
          f"{pct(max(emitted - crit, 0), emitted)} |")
print()
print("Full breakdown by code:\n")
for label, key in ROOTS:
    c = load(f"{key}_census.json")
    print(f"- **{label}**: " + ("; ".join(f"`{k}` ×{v}"
          for k, v in sorted(c["citation_checks"].items())) or "no checks recorded"))
print()

print("## 3. CAUSAL WORK — the Q5 rates\n")
print("### 3a. First, the channel. Was a criticism ever shown to a conjecturer?\n")
print("A criticism can only steer what comes next if something that makes what")
print("comes next was shown it. This is read from")
print("`workflow-context-exposure-v2.exposed_items`, the record of what each")
print("dispatch's prompt actually contained.\n")
print("| Root | LLM attacks | shown to a later conjecture dispatch | "
      "mechanical criticisms | shown | distinct critic artifacts shown |")
print("|---|---|---|---|---|---|")
for label, key in ROOTS:
    q = load(f"{key}_q5.json")["exposure"]
    print(f"| {label} | {q['n_llm_attacks_total']} | "
          f"{pct(q['n_llm_attacks_shown'], q['n_llm_attacks_total'])} | "
          f"{q['n_mechanical_total']} | "
          f"{pct(q['n_mechanical_shown'], q['n_mechanical_total'])} | {q['n_shown']} |")
print()
print("### 3b. The three rates, each against its placebo\n")
print("`Placebo` runs the identical test on the candidate BEFORE the criticism,")
print("which cannot have been influenced by it. `Coupling − Placebo` is the only")
print("column that is evidence of causal work.\n")
print("| Root | Operationalization | denominator | CouplingRate | PlaceboRate | "
      "**Coupling − Placebo** | RepairRate | NeglectRate |")
print("|---|---|---|---|---|---|---|---|")
for label, key in ROOTS:
    q = load(f"{key}_q5.json")
    for name, block in (("R1 mechanical (the commitment the target failed)",
                         q["R1_mechanical"]),
                        ("R2 prose-quote (the span the critic quoted)",
                         q["R2_prose_quote"])):
        d = block["CouplingRate_minus_Placebo"]
        print(f"| {label} | {name} | {block['denominator_measurable']} | "
              f"{rate(block['CouplingRate'])} | {rate(block['PlaceboRate'])} | "
              f"**{'—' if d is None else f'{100.0 * d:+.1f} pp'}** | "
              f"{rate(block['RepairRate'])} | {rate(block['NeglectRate'])} |")
print()
print("### 3c. Verdict breakdown (what the denominators exclude, and why)\n")
print("| Root | Operationalization | " + " | ".join(
    ["coupled", "neglected", "no-next-candidate", "no-verbatim-quote-to-track",
     "unlocatable-in-log"]) + " |")
print("|---|---|" + "---|" * 5)
for label, key in ROOTS:
    q = load(f"{key}_q5.json")
    for name, block in (("R1", q["R1_mechanical"]), ("R2", q["R2_prose_quote"])):
        v = block["verdicts"]
        cells = [str(v.get(k, 0)) for k in
                 ("coupled", "neglected", "no-next-candidate",
                  "no-verbatim-quote-to-track", "unlocatable-in-log")]
        print(f"| {label} | {name} | " + " | ".join(cells) + " |")
print()

# ------------------------------------------------------------ 4. LABEL WORK
print("## 4. LABEL WORK — which criticisms moved a Status\n")
print("`DR-CON-warrants-and-attacks`: an artifact reaches REFUTED through one")
print("chain and no other — a carried, registered warrant materializing an")
print("attack edge that the grounded extension finds accepted. The edge builder")
print("is blind to `WarrantType`, so demonstrative-vs-prose is a fact about the")
print("MINT SITE, never about force.\n")
print("| Root | att edges | from a mechanical verdict | from an LLM attack | "
      "LLM attacks carrying any warrant | criticism dispatch authority |")
print("|---|---|---|---|---|---|")
for label, key in ROOTS:
    c = load(f"{key}_census.json")
    at = [d for d in c["dispatches"] if d["outcome"] == "attack"]
    mech_edges = sum(1 for m in c["mechanical"] if m.get("attacks_target_in_att"))
    llm_edges = sum(1 for d in at if d.get("attacks_target_in_att"))
    carried = sum(1 for d in at if d.get("warrants_carried"))
    auth = collections.Counter(d.get("dispatch_authority") for d in c["dispatches"])
    astr = ", ".join(f"{k}×{v}" for k, v in auth.most_common())
    print(f"| {label} | {c['n_att_edges']} | {mech_edges} | {llm_edges} | "
          f"{carried} | {astr} |")
print()
print("### 4a. Of the refutations, demonstrative vs prose-only\n")
print("| Root | warrants | demonstrative | argumentative | fail verdicts | "
      "artifacts finally REFUTED |")
print("|---|---|---|---|---|---|")
for label, key in ROOTS:
    c = load(f"{key}_census.json")
    t = collections.Counter(m.get("warrant_type") for m in c["mechanical"])
    v = collections.Counter(m.get("claimed_verdict") for m in c["mechanical"])
    print(f"| {label} | {c['n_warrants']} | {t.get('demonstrative', 0)} | "
          f"{t.get('argumentative', 0)} | {v.get('fail', 0)} | "
          f"{c['status_counts'].get('refuted', 0)} |")
print()

# -------------------------------------------------------- 5. THE P-C1 QUESTION
print("## 5. THE P-C1 QUESTION — did criticism ever precede a score improvement?\n")
q = load("pc1_q5.json")
traj = q["best_score_trajectory"]
print("| # | log seq | new best (exact checker) | criticism events already on the record |")
print("|---|---|---|---|")
for i, t in enumerate(traj, 1):
    print(f"| {i} | {t['seq']} | {t['new_best']:.8f} | {t['criticisms_before']} |")
print()
print(f"Total criticism events in the run: **{q['n_criticism_events_total']}**. ")
print(f"Coupled changes that improved the score (R1): "
      f"**{q['R1_mechanical']['helped']} of {q['R1_mechanical']['coupled']}**. ")
print(f"Coupled changes that improved the score (R2): "
      f"**{q['R2_prose_quote']['helped']} of {q['R2_prose_quote']['coupled']}**.\n")

# ------------------------------------------------------------------ 6. SWEEP
print("## 6. The structural sweep — all 60 roots that recorded criticism\n")
s = load("sweep.json")["totals"]
print(f"- roots with criticism events: **{s['roots']}**, "
      f"criticism events: **{s['criticism_events']}**")
print(f"- critic-role artifacts: **{s['critic_artifacts_total']}**; ever shown to a "
      f"conjecture dispatch: **{s['critic_artifacts_shown_to_conjecture_total']}** "
      f"({100.0 * s['critic_artifacts_shown_to_conjecture_total'] / s['critic_artifacts_total']:.1f}%)")
print(f"- roots where at least one criticism reached a conjecturer: "
      f"**{s['roots_where_a_criticism_reached_a_conjecturer']} of {s['roots']}**")
print(f"- warrants across the tree: {s['warrant_types']}")
print(f"- criticism dispatch authority across the tree: "
      f"{s['criticism_dispatch_authority']}\n")
print("| Root | Crit events | critic artifacts | shown to a conjecturer | warrants |")
print("|---|---|---|---|---|")
rows = sorted(load("sweep.json")["roots"], key=lambda r: -r["crit_events"])[:20]
for r in rows:
    print(f"| `{r['root']}` | {r['crit_events']} | {r.get('n_critic_artifacts', 0)} | "
          f"{r.get('critic_artifacts_shown_to_conjecture', 0)} | "
          f"{r.get('warrant_types', {})} |")
