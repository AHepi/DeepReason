#!/usr/bin/env python3
"""Does ARM V's bank say anything about its targets? — SPEC S4 accept, R9.

    python check_vacuity.py --bank FILE --targets FILE [--stoplist FILE]
    python check_vacuity.py --self-test

ARM V's whole claim is that its objections carry NO CONTENT ABOUT THE TARGET.
That claim is checkable and this checks it: every content word in every bank
entry is compared against the content words of the targets it will be shown
against, and any overlap beyond a closed stop-list of ordinary English is a
FAILURE, named entry by entry and word by word.

WHY OVERLAP AND NOT SIMILARITY. A similarity score would need a threshold, and
a threshold is a knob that can be turned until the bank passes. Set overlap is
a fact: either a word from the target appears in the objection or it does not.

AND WHY THE BASELINE IS THE BANK'S OWN DECLARED VOCABULARY, NOT A STOP-LIST
THAT GROWS. The first version of this check used only a hand-written stop-list
and reported eight of twelve entries as naming their targets — on the words
"rather" and "made". Both are ordinary English with no subject matter, so the
obvious repair was to add them to the stop-list. That repair is exactly the
knob this check exists to avoid: a stop-list extended whenever the bank fails
is a stop-list fitted to the bank, and it would eventually absorb a real word.

So the baseline is not extended by hand. It is the bank's OWN generator
vocabulary — every word appearing in the committed `STEMS` and `CONTINUATIONS`
of `make_vacuous_bank.py`. That set is fixed before any target exists and
cannot be adjusted per target, so a word in it is not evidence of anything
having passed from a target to an objection. What remains after subtracting it
is the real question: a word in an entry that the generator could not have
produced. There are only two ways such a word gets there — the bank was edited,
or it was not generated by this generator — and both are exactly what ARM V
must rule out.

TWO CHECKS, therefore, and both must pass:
  (1) CLOSED VOCABULARY — every sentence of every entry is one of the committed
      clauses, verbatim. This is what makes the bank provably target-free by
      construction rather than by inspection.
  (2) TARGET OVERLAP — no content word outside the generator vocabulary and the
      small committed stop-list appears in both an entry and its targets. This
      is the belt for check (1)'s braces: it catches a bank that failed (1).

WHAT A PASS DOES NOT MEAN. It does not mean the objections are unhelpful — a
generic objection can still prompt a better candidate, and if it does, that IS
the finding ARM V exists to produce. It means only that whatever ARM V's
objections do, they do not do it by saying anything about their target.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

# Closed, committed, and deliberately small: only words that carry no subject
# matter. Anything a domain would supply -- corroboration, probability, Popper,
# induction, theory, test -- is NOT here, so an entry mentioning one fails.
STOPLIST = frozenset("""
a an and are as at be been but by can cannot could did do does for from
had has have how if in into is it its more most no not of on one only or
other our out over own same should so some such than that the their them
then there these they this those to under until up very was way we were
what when where which while who why will with without would you your
argument argued argues arguing case claim claims conclusion conclusions
position positions premise premises support supported supporting evidence
objection objections point points reading readings step steps term terms
assertion asserted stated statement scope assumption assumptions
available addressed established defended disputed drawn offered raised
matter settles settle stands survive removal carrying explicit further
strongest weaker broader firmly faster different places work rests
counter proposal difficulty answer answers gap presented rejection
nothing either way much said going exactly shared treated dispute
suggests warrants intervening alternative distinction relies used
""".split())
WORD = re.compile(r"[a-z][a-z'-]{2,}")


def generator_vocabulary() -> tuple[set[str], set[str]]:
    """The bank generator's own committed clauses and their words.

    Read from `make_vacuous_bank.py` at run time rather than copied here: two
    copies of one closed vocabulary is two things to keep in agreement, and the
    one that drifted would silently widen what this check tolerates.
    """
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
    import make_vacuous_bank  # noqa: PLC0415

    clauses = set(make_vacuous_bank.STEMS) | set(make_vacuous_bank.CONTINUATIONS)
    words = set(WORD.findall(" ".join(clauses).lower()))
    return clauses, words


def content_words(text: str, baseline: set[str]) -> set[str]:
    return {w for w in WORD.findall(text.lower())
            if w not in STOPLIST and w not in baseline}


def check(bank: dict, targets: list[str]) -> dict:
    clauses, baseline = generator_vocabulary()

    # (1) closed vocabulary: every sentence must be a committed clause.
    off_vocabulary = []
    for entry in bank["entries"]:
        for sentence in entry["text"].rstrip(".").split(". "):
            if sentence.strip() not in clauses:
                off_vocabulary.append({"index": entry["index"],
                                       "sentence": sentence.strip()[:120]})

    # (2) target overlap, over what the generator could NOT have produced.
    target_words: set[str] = set()
    for target in targets:
        target_words |= content_words(target, baseline)
    findings = []
    for entry in bank["entries"]:
        overlap = sorted(content_words(entry["text"], baseline) & target_words)
        if overlap:
            findings.append({"index": entry["index"], "overlap": overlap})

    vacuous = not off_vocabulary and not findings
    return {
        "schema": "vacuity-check.v2",
        "bank_digest": bank.get("digest"),
        "entries": len(bank["entries"]),
        "targets": len(targets),
        "generator_vocabulary_words": len(baseline),
        "distinct_target_content_words": len(target_words),
        "entries_off_vocabulary": len(off_vocabulary),
        "off_vocabulary": off_vocabulary[:10],
        "entries_naming_their_targets": len(findings),
        "findings": findings,
        "verdict": "VACUOUS" if vacuous else "NOT VACUOUS",
    }


def self_test() -> int:
    """Green on a real bank, and RED on the same bank with one planted entry.

    The planted entry is what makes this check worth running: a check that has
    never been shown to fail is indistinguishable from one that cannot.
    """
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
    import make_vacuous_bank  # noqa: PLC0415

    targets = [
        "Corroboration is not probability: a theory that has survived severe "
        "tests is not thereby made more probable, and Popper's preference for "
        "the better-corroborated theory therefore smuggles induction back in.",
        "The pragmatic reading dissolves the tension by redefining "
        "corroboration as a report on past performance rather than a "
        "prediction about future reliability.",
    ]
    bank = make_vacuous_bank.build(median=600, iqr=(400, 900), count=12,
                                   seed=20260909)
    clean = check(bank, targets)
    print(f"clean bank: {clean['verdict']} "
          f"({clean['entries_off_vocabulary']} of {clean['entries']} entries "
          f"off-vocabulary, {clean['entries_naming_their_targets']} naming "
          f"their targets; generator vocabulary "
          f"{clean['generator_vocabulary_words']} words, "
          f"{clean['distinct_target_content_words']} distinct target content "
          f"words outside it were searched for)")
    if clean["verdict"] != "VACUOUS":
        print(json.dumps(clean, indent=1))
        return 1

    planted = json.loads(json.dumps(bank))
    planted["entries"][3]["text"] = (
        "The argument's treatment of corroboration as a guide to future "
        "reliability is exactly where the induction Popper rejected returns.")
    dirty = check(planted, targets)
    print(f"planted bank: {dirty['verdict']} "
          f"({dirty['entries_off_vocabulary']} entry off-vocabulary, "
          f"{dirty['entries_naming_their_targets']} naming its target: "
          f"{dirty['findings'][0]['overlap'] if dirty['findings'] else []})")
    if dirty["verdict"] != "NOT VACUOUS":
        print("MUTATION DID NOT FAIL: this check cannot detect a "
              "target-specific objection and is worthless")
        return 1
    print("the check goes RED on a planted target-specific objection, so a "
          "pass above is a fact rather than an absence of testing")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--bank", default=None)
    ap.add_argument("--targets", default=None,
                    help="JSON list of target texts, or a run root's composed unit")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        return self_test()
    if not args.bank or not args.targets:
        ap.error("--bank and --targets are required")
    bank = json.loads(pathlib.Path(args.bank).read_text(encoding="utf-8"))
    raw = pathlib.Path(args.targets).read_text(encoding="utf-8")
    targets = json.loads(raw) if raw.lstrip().startswith("[") else [raw]
    result = check(bank, targets)
    print(json.dumps(result, indent=1, sort_keys=True))
    return 0 if result["verdict"] == "VACUOUS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
