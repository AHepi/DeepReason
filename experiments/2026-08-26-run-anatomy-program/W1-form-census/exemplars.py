"""W1 — EXEMPLARS.md: the blobs behind the numbers, quoted verbatim.

Blob-first discipline (CLAUDE.md): a count is a claim about bytes, and the
bytes are quotable. Every exemplar below names its root, its log sequence and
its blob ref, so a reader can `cat` the same file and check the quote.

Regenerate with `python3 exemplars.py`. Nothing here is hand-written.
"""
from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import census as C  # noqa: E402


def blob_path(root_rel: str, ref: str) -> str:
    ref = (ref or "").split(":")[-1]
    return f"{root_rel}/blobs/{ref[:2]}/{ref}"


def load(root_rel: str) -> dict:
    return json.load(open(os.path.join(HERE, "census", f"{C.slug(root_rel)}.json")))


def quote(text: str, limit: int = 1400) -> str:
    body = (text or "").rstrip()
    if len(body) > limit:
        body = body[:limit] + f"\n… [truncated at {limit} bytes for this page; "
        body += "the blob on disk is complete]"
    # A quoted blob frequently CONTAINS a ```json fence of its own — that is
    # itself one of the census's findings — so the wrapper must be longer than
    # anything it can wrap, or the page renders as nonsense from here down.
    fence = "`" * max(4, max((len(m) for m in _fence_runs(body)), default=3) + 1)
    return fence + "\n" + body + "\n" + fence


def _fence_runs(text: str) -> list:
    runs, count = [], 0
    for ch in text:
        if ch == "`":
            count += 1
        else:
            if count:
                runs.append("`" * count)
            count = 0
    if count:
        runs.append("`" * count)
    return runs


def section(out: list, title: str, why: str) -> None:
    out += ["", f"## {title}", "", why, ""]


def main() -> int:
    docs = [load(r["root"]) for r in json.load(
        open(os.path.join(os.path.dirname(HERE), "ROOT_INVENTORY.json")))["roots"]]
    by_root = {d["root"]: d for d in docs}
    out = [
        "# Exemplars — the blobs behind the numbers",
        "",
        "Generated by `exemplars.py`; do not hand-edit. Every quote names its",
        "root, log sequence and blob path, so it can be checked against the",
        "committed record with `cat <path>`.",
    ]

    # 1 — a field name in the wrong language
    section(
        out,
        "A field name in the wrong language",
        "The invalid-arrival taxonomy's largest wire-level class is a field the "
        "contract does not declare. This one is not a typo: the model wrote a "
        "German word where an English field name belongs, inside otherwise "
        "well-formed JSON.",
    )
    found = False
    for d in docs:
        for r in d["rows"]:
            for f in r["failures"]:
                if "preise" in (f["message"] or ""):
                    out += [
                        f"Root `{d['root']}`, log seq {r['seq']}, contract "
                        f"`{r['contract_id']}`, role `{r['role']}`, model `{r['model']}`.",
                        "",
                        "Diagnostic, verbatim:",
                        quote(f["message"]),
                    ]
                    found = True
                    break
            if found:
                break
        if found:
            break

    # 2 — coerced fabrication where omission was legal
    section(
        out,
        "A handle invented where the record said omission was legal",
        "The coercion probe's CFR rests on diagnostics that carry "
        "`omission_or_unknown_legal: true` — the record itself telling the seat, "
        "in the instruction text, that leaving the field out was a valid repair. "
        "This is one such diagnostic, quoted whole.",
    )
    for d in docs:
        stop = False
        root = os.path.join(C.REPO, d["root"])
        for r in d["rows"]:
            for f in r["failures"]:
                if f["omission_or_unknown_legal"] is True and f["observed_handle_kind"] == "unknown":
                    out += [
                        f"Root `{d['root']}`, log seq {r['seq']}, contract "
                        f"`{r['contract_id']}`, model `{r['model']}`.",
                        "",
                        "The diagnostic the harness wrote:",
                        quote(json.dumps({k: v for k, v in f.items() if k != "kind"}, indent=1)),
                    ]
                    _, raw = C.read_blob(root, r["raw_ref"])
                    out += [
                        "",
                        f"What the model sent (`{blob_path(d['root'], r['raw_ref'])}`):",
                        quote(raw, 900),
                    ]
                    stop = True
                    break
            if stop:
                break
        if stop:
            break

    # 3 — lossless-spelling survivors after the fix
    section(
        out,
        "The lossless-spelling class after its fix",
        "`experiments/2026-08-22-fix-repair-patch-transport` (commit 97a964583, "
        "2026-08-22T16:09:24Z) absorbs four container names, three harness "
        "echoes and the `pointer`→`path` rename. Five attempts across two roots "
        "that ran AFTER that commit still lose a repair grant to a spelling. "
        "Each is quoted whole, because what matters is exactly which byte the "
        "fix's closed key set does not cover.",
    )
    for d in docs:
        if (d["first_ts"] or "") < "2026-08-22T16:09:24+00:00":
            continue
        root = os.path.join(C.REPO, d["root"])
        for r in d["rows"]:
            hits = [
                f["field_raw"]
                for f in r["failures"]
                if f["class"] == "extra_forbidden"
                and f["field_raw"] in C.ECHO_OR_CONTAINER_POINTERS
            ]
            if not hits:
                continue
            _, raw = C.read_blob(root, r["raw_ref"])
            out += [
                f"**Root `{d['root']}`, log seq {r['seq']}, contract "
                f"`{r['contract_id']}`, model `{r['model']}` — rejected at `{hits[0]}`.**",
                "",
                quote(raw, 700),
                "",
            ]

    # 4 — a construction that scores exactly zero
    section(
        out,
        "A P-C1 construction whose minimum triangle area is exactly zero",
        "126 of ARM H's 133 constructions place three or more points on a shared "
        "x or y coordinate. Three points on a line have zero area, and the "
        "minimum over all triples is therefore zero — whatever the CLAIM line "
        "says. The form is filled correctly; the content is degenerate.",
    )
    head = json.load(open(os.path.join(HERE, "PC1_HEADLINE.json")))
    ex = head["mechanism"]["arm_h"]["exemplars"].get("score_zero")
    if ex:
        out += [
            "Checker verdict (from the tranche's own committed `checker.py`):",
            quote(json.dumps(ex["verdict"], indent=1)),
            "",
            "Signature — how many points share a coordinate:",
            quote(json.dumps(ex["signature"], indent=1)),
            "",
            "The construction the model wrote:",
            quote(ex["construction"], 900),
        ]

    # 5 — an attack with no case
    section(
        out,
        "An attack asserted with no case",
        "`batch-critic.v2` requires a boolean `attack` per target and lets `case` "
        "default to the empty string. 15 of 1453 asserted attacks carry no case "
        "text at all: the form records an attack the seat never argued.",
    )
    probe = json.load(open(os.path.join(HERE, "COERCION_PROBE.json")))
    empties = [e for e in probe["forced_boolean_vs_sibling_prose"]["exemplars"] if e["case_is_empty"]]
    if empties:
        e = empties[0]
        d = by_root.get(e["root"])
        row = next((r for r in d["rows"] if r["seq"] == e["seq"]), None) if d else None
        if row:
            _, raw = C.read_blob(os.path.join(C.REPO, e["root"]), row["raw_ref"])
            out += [
                f"Root `{e['root']}`, log seq {e['seq']}, model `{e['model']}`.",
                "",
                f"The response, verbatim (`{blob_path(e['root'], row['raw_ref'])}`):",
                quote(raw, 1200),
            ]

    # 6 — the one self-referential refusal that still asserted an attack
    section(
        out,
        "The one asserted attack whose prose says the critic cannot",
        "Reported as one case and quoted in full rather than counted, because "
        "the reading is genuinely borderline: `I cannot` may be the critic "
        "declining, or may be part of the criticism. A reader should decide "
        "from the bytes, not from this census's word list.",
    )
    refused = [e for e in probe["forced_boolean_vs_sibling_prose"]["exemplars"] if e["refusal_phrases"]]
    if refused:
        e = refused[0]
        d = by_root.get(e["root"])
        row = next((r for r in d["rows"] if r["seq"] == e["seq"]), None) if d else None
        if row:
            _, raw = C.read_blob(os.path.join(C.REPO, e["root"]), row["raw_ref"])
            out += [
                f"Root `{e['root']}`, log seq {e['seq']}, model `{e['model']}`, "
                f"`attack: true`.",
                "",
                quote(raw, 1600),
            ]

    # 7 — truncation
    section(
        out,
        "A response cut off mid-JSON, and what the harness asked for next",
        "`TRUNCATED_MID_JSON` is the record's own diagnostic when the completion "
        "cap lands inside the object. The diagnostic text is the instruction the "
        "seat then receives, so it shows both the failure and the ask.",
    )
    for d in docs:
        stop = False
        for r in d["rows"]:
            for f in r["failures"]:
                if f["class"] == "TRUNCATED_MID_JSON":
                    out += [
                        f"Root `{d['root']}`, log seq {r['seq']}, contract "
                        f"`{r['contract_id']}`, model `{r['model']}`, "
                        f"tokens {r['tokens']} against max_tokens {r['max_tokens']}.",
                        "",
                        quote(f["message"]),
                    ]
                    stop = True
                    break
            if stop:
                break
        if stop:
            break

    with open(os.path.join(HERE, "EXEMPLARS.md"), "w") as fh:
        fh.write("\n".join(out).rstrip() + "\n")
    print(f"EXEMPLARS.md written ({len(out)} lines of source)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
