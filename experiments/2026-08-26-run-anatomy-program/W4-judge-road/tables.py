#!/usr/bin/env python3
"""Emit W4's two generated tables from the committed census JSONs.

Nothing here types a number. `python3 tables.py` writes FUNNEL.md and
ADJUDICATION_SAMPLE.md; if a figure appears in either file and not in one
of the JSONs, it is not this tranche's figure.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROAD = json.loads((HERE / "road_census.json").read_text())
SWEEP = json.loads((HERE / "trial_sweep.json").read_text())
HAND = json.loads((HERE / "handcheck.json").read_text())
SAMPLE = json.loads((HERE / "verdict_sample.json").read_text())
PROXY = json.loads((HERE / "criterion_proxy_probe.json").read_text())

GATE_NAMES = {
    "U0": "a batch criticism dispatch happens",
    "U1": "the response parses into cases",
    "U2": "`attack: true` with non-empty case text",
    "U3": "`try_counterexample` does NOT ground it",
    "U4": "execution supremacy does NOT take it",
    "U5": "**THE AUTHORITY GATE** — `trial_required`, not `observe_only`",
    "U6": "an adapter exists (not crash recovery)",
    "T1": "defender and judge roles present",
    "T2": "target resolvable",
    "T3": "ensemble adequate for the run's topology",
    "T4": "formal supremacy does not take it (`execution-backed`)",
    "T5": "non-empty case",
    "T6": "judge ensemble unanimous (`ensemble-split`)",
    "T7": "the unanimous verdict is `fail` (`defence-sustained`)",
    "T8": "every `decisive_point` quotes the exchange (`referential-integrity`)",
    "T9": "paraphrase invariance (`paraphrase-flip` / re-ruling split)",
    "T10": "**WARRANT MINTED**",
}


def funnel() -> str:
    out = ["# W4 — the judge-road funnel", ""]
    out.append(
        "Generated by `python3 tables.py` from `road_census.json` and "
        "`trial_sweep.json`. Every gate is transcribed from source order in "
        "`rules/crit.py::_crit_argumentative_batch_result` (leg 1) and "
        "`informal/trial.py::_argument_trial_steps` (leg 2); every count is "
        "a typed marker in `log.jsonl` or a warrant in `objects/`."
    )
    out.append("")
    out.append(
        "**Read leg 1 and leg 2 differently, because the record supports "
        "them differently.** Leg 2 is an EXACT CHAIN: every trial that "
        "enters `_argument_trial_steps` leaves by exactly one door, so the "
        "remainder column is a subtraction and closes on the minted count. "
        "Leg 1 is NOT a chain: its stages are measured independently — "
        "dispatches and cases from each critic call's own raw completion "
        "blob, terminators from their typed Measures — and they need not "
        "reconcile to the row, because a batch can name a target twice or "
        "name one outside the batch (both `continue` with no marker at "
        "all), and a completion blob that will not parse is counted "
        "unreadable rather than dropped. Where the two disagree the gap is "
        "printed, never smoothed."
    )
    out.append("")
    for name, row in sorted(ROAD["roots"].items()):
        head = row["funnel_head"]
        cfg = next(r["config"] for r in SWEEP["roots"] if r["root"] == row["root"])
        d = row["declines_by_gate"]
        entered = row["trials_entered"]
        minted = row["trials_sustained_warrant_minted"]
        out.append(f"## {name} — `{row['root']}`")
        out.append("")
        out.append(
            f"Manifest `criticism_policy.authority`: "
            f"**{cfg['criticism_policy_authority']}** · judge seats frozen "
            f"into the manifest: {cfg['judge_seats_declared']} · defender "
            f"seats: {cfg['defender_seats_declared']} · compile notices: "
            f"{cfg.get('compile_notices', 'none')}"
        )
        out.append("")
        out.append("### Leg 1 — from a criticism dispatch to the trial door")
        out.append("")
        out.append("| stage | gate | measured | typed marker |")
        out.append("|---|---|---:|---|")
        out.append(
            f"| U0 | a batch criticism dispatch happens | "
            f"{head['U0_dispatches']} | `LLMCall(role=argumentative_critic)` |"
        )
        out.append(
            f"| U1 | the completion parses into cases | "
            f"{head['U1_cases_returned']} | raw completion blob "
            f"({head['dispatch_blobs_unreadable']} unreadable) |"
        )
        out.append(
            f"| U2 | `attack: true` | {head['U2_cases_claiming_attack']} | "
            f"— ({head['U1_cases_returned'] - head['U2_cases_claiming_attack']}"
            " declined to attack; no marker) |"
        )
        out.append(
            f"| U2 | ...and non-empty case text | "
            f"{head['U2_cases_attack_with_non_empty_text']} | — |"
        )
        for gate, label, marker in (
            ("U4", "execution supremacy takes it", "`arg-crit-overridden-by-execution`"),
            ("U5", "**THE AUTHORITY GATE** — observed only", "`scrutiny`"),
            ("U6", "no adapter (crash recovery)", "`defended-trial-deferred`"),
        ):
            out.append(
                f"| {gate} | {label} | {row['leg1_terminators'].get(gate, 0)} | "
                f"{marker} |"
            )
        out.append(
            f"| → | **entered `_argument_trial_steps`** | {entered} | "
            "`trial-declined` + minted `w:argtrial:` warrants |"
        )
        out.append("")
        gap = head["U2_cases_attack_with_non_empty_text"] - (
            row["leg1_terminators"].get("U5", 0) + entered
        )
        out.append(
            f"Gap between U2 (non-empty attacking cases) and U4 + U5 + "
            f"trials entered: **{gap}**, from dedup / out-of-batch targets "
            f"and from cases behind the "
            f"{head['dispatch_blobs_unreadable']} unreadable completion "
            "blobs. Stated, not smoothed."
        )
        if row["leg1_terminators"].get("U6"):
            out.append("")
            out.append(
                f"U6 is deliberately EXCLUDED from that arithmetic. The "
                f"{row['leg1_terminators']['U6']} `defended-trial-deferred` "
                "Measures are emitted by crash recovery, which has no "
                "provider boundary by design (`rules/crit.py`, "
                "SEAM-llm-x-workflow): the case is left OPEN for a later "
                "live cycle to reconsider. A deferred case can therefore "
                "ALSO appear as one of the trials entered above, and this "
                "census cannot tell which of the 119 did. Counting them in "
                "the same column would double-count them; counting them "
                "nowhere would hide a real road terminator. They are "
                "reported here, unreconciled."
            )
        out.append("")
        out.append("### Leg 2 — inside the trial")
        out.append("")
        if not entered:
            out.append(
                "No trial was entered, so leg 2 has no rows. The road ended "
                "at **U5, the authority gate**."
            )
            out.append("")
            continue
        out.append("| gate | what it demands | arrives | leaves here |")
        out.append("|---|---|---:|---|")
        remaining = entered
        for gate, marker in (
            ("T1", "`no-defender-role` / `no-judge-role`"),
            ("T2", "`unknown-target`"),
            ("T3", "`single-judge-seat` / `no-critic-school` / `same-school-critic`"),
            ("T4", "`execution-backed`"),
            ("T5", "`empty-case`"),
            ("T6", "`ensemble-split` (first ruling)"),
            ("T7", "`defence-sustained`"),
            ("T8", "`referential-integrity`"),
            ("T9", "`paraphrase-flip` / re-ruling `ensemble-split`"),
        ):
            left = d.get(gate, 0)
            out.append(
                f"| {gate} | {GATE_NAMES[gate]} | {remaining} | {left} — {marker} |"
            )
            remaining -= left
        out.append(f"| T10 | {GATE_NAMES['T10']} | {remaining} | — |")
        out.append("")
        out.append(
            f"Chain closes: {entered} entered − {row['trials_declined']} "
            f"declined = {minted} minted, and `objects/warrant/` holds "
            f"exactly {minted} `w:argtrial:` warrants."
        )
        out.append("")
        out.append(
            f"Seats spent: judge {row['dispatches_by_role']['judge']} · "
            f"defender {row['dispatches_by_role']['defender']} · variator "
            f"{row['dispatches_by_role']['variator']}. Refused at the door "
            f"before any seat spent (T1–T5): "
            f"{row['trials_refused_at_the_door']}; actually convened: "
            f"{row['trials_convened_judge_spent']}."
        )
        out.append("")
        out.append(
            "Warrants by mint site: `"
            + json.dumps(row["warrants"]["by_mint_site"])
            + "`"
        )
        out.append("")
        out.append(
            "`ensemble-split` is spelled identically at T6 and T9 "
            "(deliberately — trial.py: renaming it \"would change what "
            "those roots\' diagnostics mean\"). Both structural "
            "discriminators — a variator call since this trial\'s defender "
            "call, and more than one ensemble ruling spent since it — "
            f"agreed on every split; {row['ensemble_split_unplaced']} "
            "unplaced."
        )
        out.append("")
    t = SWEEP["totals"]
    out.append("## The standing fact, re-derived over all 54 roots")
    out.append("")
    out.append("| | n |")
    out.append("|---|---:|")
    for key in (
        "roots",
        "roots_declaring_judge_seats",
        "roots_with_criticism_policy",
        "roots_with_any_judge_call",
        "roots_with_ran_true",
        "judge_calls",
        "trial_declined",
        "trial_observations",
        "trial_blocked",
        "crit_events",
    ):
        out.append(f"| {key.replace('_', ' ')} | {t[key]} |")
    out.append("")
    out.append(
        "Manifest `criticism_policy.authority` across the 54 roots: `"
        + json.dumps(t["criticism_policy_authorities"])
        + "` — the four `defended_trial` roots are all the same run id "
        "`8e22d0431fd2b98d`, and the three that are not GEX died at cycle 0 "
        "with zero criticism events."
    )
    out.append("")
    return "\n".join(out) + "\n"


def adjudication() -> str:
    by_key = {(r["root"], r["seq"], r["commitment"]): r for r in HAND["rows"]}
    out = ["# W4 — the 60-row commitment-verdict hand sample", ""]
    out.append(
        "Generated by `python3 tables.py` from `handcheck.json` and "
        "`verdict_sample.json`. `verdict_sample.py` selects the rows and "
        "resolves the artifact bytes; `handcheck.py` re-derives each "
        "predicate WITHOUT importing `deepreason`, and prints the decisive "
        "fact a reader checks by eye. A `fail` verdict means the "
        "commitment's predicate evaluated FALSE on the artifact's content."
    )
    out.append("")
    for root_name, root in SAMPLE["roots"].items():
        tally = HAND["tally"][root_name]
        out.append(f"## {root_name} — `{root['root_path']}`")
        out.append("")
        out.append(
            f"{len(root['sample'])} of {root['verdicts_available']} verdicts. "
            "Ruling tally: " + ", ".join(f"**{k} {v}**" for k, v in sorted(tally.items()))
        )
        out.append("")
        out.append("| seq | commitment | verdict | independent | ruling | decisive fact |")
        out.append("|---:|---|---|---|---|---|")
        for entry in root["sample"]:
            row = by_key[(root_name, entry["seq"], entry["commitment"])]
            check = row["check"]
            if check["family"] == "geometry":
                decisive = check.get("decisive", "")
            else:
                decisive = " AND ".join(
                    f"{c['n_found']}/{c['floor']} {c['found'] or '—'}"
                    for c in check["clauses"]
                )
            decisive = decisive.replace("|", "\\|")
            holds = row["independent_predicate_holds"]
            out.append(
                f"| {entry['seq']} | `{entry['commitment']}` | "
                f"{entry['recorded_verdict']} | predicate {holds} | "
                f"**{row['ruling']}** | {decisive[:150]} |"
            )
        out.append("")
    out.append("## Criterion quality, measured separately from ruling quality")
    out.append("")
    out.append(
        f"`{PROXY['criterion']}` requires one of nine listed distribution "
        "spellings. The operator's question writes the distribution as "
        "\"the 3-of-26 result\" and \"compile.py 1/9 mutations lost\"; the "
        "hyphenated spellings are not on the list. Over all "
        f"{PROXY['artifacts_with_inline_content']} P-R1 artifacts with inline "
        "content, "
        f"**{PROXY['artifacts_invisible_to_the_criterion_but_naming_the_distribution']}** "
        "name the distribution in the question's own hyphenated spelling and "
        "match nothing on the criterion's list, and "
        f"**{PROXY['of_those_refuted_on_this_criterion']} of the "
        f"{PROXY['verdicts_on_this_criterion_in_the_run']}** verdicts this "
        "criterion issued in the whole run landed on one of them. Every one "
        "of those verdicts is CORRECT as specified. The criterion is the "
        "thing at fault, not the ruling."
    )
    out.append("")
    return "\n".join(out) + "\n"


def main() -> int:
    (HERE / "FUNNEL.md").write_text(funnel())
    (HERE / "ADJUDICATION_SAMPLE.md").write_text(adjudication())
    print("wrote FUNNEL.md ADJUDICATION_SAMPLE.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
