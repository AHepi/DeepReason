"""Render the W5 census JSON into the committed tables.

Every number here is read out of SIGNAL_CENSUS.json, CONTROLLER_CENSUS.json,
STALENESS.json and LAW_CHECK.json — this module computes nothing of its own,
so a table and its JSON can never drift.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def load(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as handle:
        return json.load(handle)


def short(root):
    return root.replace("experiments/", "")


def write(name, lines):
    with open(os.path.join(HERE, name), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines).rstrip() + "\n")
    print(f"wrote {name}")


