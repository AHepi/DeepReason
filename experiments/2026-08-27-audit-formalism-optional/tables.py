"""Part 2 — the kind-outcome tables, from KIND_CENSUS.json (+ ADMISSION_CENSUS.json).

    python experiments/2026-08-27-audit-formalism-optional/tables.py

Writes TABLES.md.  Counts, never rates alone: every cell shows n/N so a reader
can see the denominator that produced the percentage.

Correlation is not causation, and it is worth saying twice: a battery-carrying
artifact and a prose one are not the same content.  A battery is compiled from
the PROBLEM's criteria (`workloads/models.py:101`), so within one problem the
split usually tracks WHICH ROLE minted the artifact and which harness-owned
mandatory commitments it drew, not how formal the model's writing was.  These
tables show what the record did.  They cannot separate a kind effect from a
content effect, and the residue section of RESULTS.md says so in full.
"""

import json
import os
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
SPLITS = [
    ("K1 battery-carrying", "battery_carrying"),
    ("K2 substantive-backed", "substantive_backed"),
    ("K3 execution-backed", "execution_backed"),
]
OUTCOMES = [
    ("accepted", lambda r: r["status"] == "accepted"),
    ("refuted", lambda r: r["status"] == "refuted"),
    ("survivor", lambda r: r["survivor"]),
    ("attacked at least once", lambda r: r["attacks_received"] > 0),
    ("carries a DEMONSTRATIVE warrant", lambda r: r["warrants_demonstrative"] > 0),
    ("carries an ARGUMENTATIVE warrant", lambda r: r["warrants_argumentative"] > 0),
    ("reach > 0", lambda r: r["reach"] > 0),
    ("on the Pareto frontier", lambda r: r["on_frontier"]),
    ("in the knowledge view", lambda r: r["in_knowledge_view"]),
]


def _pct(n, total):
    return f"{n}/{total} ({100.0 * n / total:.1f} %)" if total else f"0/0 (—)"


def _table(rows, field, title, note=""):
    formal = [r for r in rows if r[field]]
    prose = [r for r in rows if not r[field]]
    lines = [f"### {title}", ""]
    if note:
        lines += [note, ""]
    lines += [
        f"n = {len(rows)} artifacts — **{len(formal)}** formal-by-this-reading, "
        f"**{len(prose)}** prose-by-this-reading.",
        "",
        "| outcome | formal | prose | gap (pp) |",
        "|---|---|---|---|",
    ]
    for name, test in OUTCOMES:
        a = sum(1 for r in formal if test(r))
        b = sum(1 for r in prose if test(r))
        ra = 100.0 * a / len(formal) if formal else None
        rb = 100.0 * b / len(prose) if prose else None
        gap = f"{ra - rb:+.1f}" if ra is not None and rb is not None else "—"
        lines.append(f"| {name} | {_pct(a, len(formal))} | {_pct(b, len(prose))} | {gap} |")
    mean = lambda xs, key: (sum(r[key] for r in xs) / len(xs)) if xs else 0.0
    lines += [
        f"| *mean attacks received* | {mean(formal, 'attacks_received'):.2f} | "
        f"{mean(prose, 'attacks_received'):.2f} | "
        f"{mean(formal, 'attacks_received') - mean(prose, 'attacks_received'):+.2f} |",
        "",
    ]
    return lines


def main():
    census = json.load(open(os.path.join(HERE, "KIND_CENSUS.json")))
    try:
        admission = json.load(open(os.path.join(HERE, "ADMISSION_CENSUS.json")))
    except FileNotFoundError:
        admission = None

    named = {label: path for label, path in census["named_roots"]}
    by_root = {doc["root"]: doc for doc in census["roots"]}
    every = [r for doc in census["roots"] for r in doc["artifacts"]]

    lines = [
        "<!-- generated by tables.py; do not hand-edit -->",
        "# TABLES — kind against outcome, over the committed record",
        "",
        f"Roots read: **{census['roots_read']}** of {census['roots_attempted']} "
        f"attempted. Artifacts: **{len(every)}**.",
        "",
        "## The operationalization",
        "",
        "`Artifact` carries no kind field. Formal-vs-informal is a fact about "
        "`Interface.commitments`, read three ways — exactly the three the code "
        "itself reads:",
        "",
        "| reading | test | what in the code reads it |",
        "|---|---|---|",
        "| **K1 battery-carrying** | ≥1 registered commitment with `programs.evaluable` "
        "true | `coverage` (the Pareto axis), `_evaluable_battery`, `crit_program` |",
        "| **K2 substantive-backed** | ≥1 registered SUBSTANTIVE commitment "
        "(`measures/reach._substantive` — evaluable and not structural well-formedness) "
        "| `formally_backed`, the prose-immunity guard |",
        "| **K3 execution-backed** | ≥1 commitment in `oracle.EXEC_PROGRAMS` | "
        "`execution_backed`, `_standing_recrit_pool` |",
        "",
        "K3 ⊆ K2 ⊆ K1. \"Prose\" in each table means NOT formal by that reading.",
        "",
        "CONTENT FORM (does the artifact's own text parse as an envelope or a "
        "skeleton) is reported separately below and is never substituted for the "
        "three above: it is what a reader would call formal-looking, and it is not "
        "what any guard consults.",
        "",
    ]

    # content-form cross-tab
    cross = Counter((r["content_form"], r["battery_carrying"]) for r in every)
    forms = sorted({f for f, _ in cross})
    lines += [
        "### Content form against K1 — the two do not line up",
        "",
        "| content form | battery-carrying | not |",
        "|---|---|---|",
    ]
    for form in forms:
        lines.append(f"| {form} | {cross[(form, True)]} | {cross[(form, False)]} |")
    lines += [
        "",
        "This cross-tab is the reason the tables below use the commitment "
        "readings and not the text's appearance.",
        "",
        "---",
        "",
        "## All roots pooled",
        "",
    ]
    for title, field in SPLITS:
        lines += _table(every, field, title)

    # ---- the population the LAW is about ---------------------------------
    candidate_rows = [r for r in every if r["role"] in ("conjecturer", "synthesizer")]
    role_counts = Counter(r["role"] for r in every)
    lines += [
        "---",
        "",
        "## Candidate-role artifacts only — the population the law is about",
        "",
        "The pooled tables above mix populations, and the mix is not innocent: "
        + ", ".join(f"`{role}` {n}" for role, n in role_counts.most_common())
        + ". A `critic` artifact is prose and is never a survivor addressing a "
        "problem, so pooling drags every prose row toward zero on the outcomes "
        "only survivors can have. The operator's law is about CONJECTURES. "
        "Restricted to `conjecturer` and `synthesizer` roles:",
        "",
    ]
    for title, field in SPLITS:
        lines += _table(candidate_rows, field, f"candidate-role only — {title}")

    # ---- roots where both kinds actually coexist --------------------------
    lines += [
        "### The only two roots where formal and prose conjectures coexist",
        "",
        "A gap between kinds can only be read where both are present. Of the "
        f"{census['roots_read']} roots read, exactly two carry conjecturer-role "
        "artifacts of both kinds:",
        "",
        "| root | formal | prose | formal on frontier | prose on frontier |",
        "|---|---|---|---|---|",
    ]
    for doc in census["roots"]:
        cand = [r for r in doc["artifacts"] if r["role"] in ("conjecturer", "synthesizer")]
        formal = [r for r in cand if r["battery_carrying"]]
        prose = [r for r in cand if not r["battery_carrying"]]
        if not (formal and prose):
            continue
        lines.append(
            f"| `{doc['root']}` | {len(formal)} | {len(prose)} | "
            f"{sum(1 for r in formal if r['on_frontier'])}/{len(formal)} | "
            f"{sum(1 for r in prose if r['on_frontier'])}/{len(prose)} |"
        )
    lines += ["", "---", "", "## The named roots, one at a time", ""]
    for label, path in census["named_roots"]:
        doc = by_root.get(path)
        if doc is None:
            lines += [f"### {label} — NOT READ", "",
                      f"`{path}` is not in KIND_CENSUS.json.", ""]
            continue
        lines += [f"## {label} — `{path}`", "",
                  f"{doc['n_artifacts']} artifacts."]
        if doc.get("frontier_error"):
            lines.append(f"Frontier unavailable: `{doc['frontier_error']}` — "
                         "the frontier row below reads 0/N and is NOT MEASURED, "
                         "not measured-as-zero.")
        if doc.get("knowledge_error"):
            lines.append(f"Knowledge view unavailable: `{doc['knowledge_error']}`.")
        lines.append("")
        for title, field in SPLITS:
            lines += _table(doc["artifacts"], field, f"{label} — {title}")

    if admission is not None:
        lines += ["---", "", "## Admission — what the model wrote against what became an artifact", ""]
        lines += [
            "The denominator is every candidate object in a conjecturer's RAW "
            "provider response, parsed from the blob — including candidates that "
            "never survived wire validation, which is the population the P-C2b "
            "incident was about. `offers_checker` is the one formality signal a "
            "candidate can carry in its own wire output (`checker_specs`, or a "
            "`checker_spec` on a forbidden case / countercondition).",
            "",
            "| root | conjecturer calls | candidates written | prose-only | with a checker | artifacts minted | admission rate |",
            "|---|---|---|---|---|---|---|",
        ]
        tot_w = tot_m = tot_c = 0
        for doc in admission["roots"]:
            wrote = doc["candidates_written_total"]
            mint = doc["artifacts_minted_total"]
            checker = doc["candidates_written"].get("with_checker", 0)
            tot_w += wrote
            tot_m += mint
            tot_c += checker
            label = doc.get("label") or doc["root"].split("/")[-2:]
            rate = f"{100.0 * mint / wrote:.1f} %" if wrote else "—"
            lines.append(
                f"| {doc.get('label') or '`' + doc['root'] + '`'} | "
                f"{doc['conjecturer_calls'].get('total', 0)} | {wrote} | "
                f"{doc['candidates_written'].get('prose_only', 0)} | {checker} | "
                f"{mint} | {rate} |"
            )
        lines += [
            f"| **all roots** | | **{tot_w}** | **{tot_w - tot_c}** | **{tot_c}** | "
            f"**{tot_m}** | **{100.0 * tot_m / tot_w:.1f} %** |" if tot_w else "",
            "",
            "**The candidate-side formality channel is essentially unused.** With "
            f"{tot_c} of {tot_w} written candidates offering a checker, the "
            "admission comparison BY CANDIDATE KIND has no denominator worth "
            "quoting on the formal side. That absence is itself the measurement: "
            "the optional formal channel is available and the model does not take "
            "it, so no admission penalty for declining it can be observed — and "
            "none can be ruled out either.",
            "",
        ]

    open(os.path.join(HERE, "TABLES.md"), "w").write("\n".join(lines) + "\n")
    print(f"wrote TABLES.md over {len(every)} artifacts in {census['roots_read']} roots")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
