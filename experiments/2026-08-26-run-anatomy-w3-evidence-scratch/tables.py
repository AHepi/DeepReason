#!/usr/bin/env python3
"""Render TABLES.md from the two census JSONs. Presentation only -- this
script derives no number of its own; every figure is read straight out of
evidence_census.json or scratch_census.json."""
from __future__ import annotations

import json
import pathlib

T = pathlib.Path(__file__).resolve().parent
EV = json.loads((T / "evidence_census.json").read_text())
SC = json.loads((T / "scratch_census.json").read_text())
PR1 = next(r for r in EV["roots"] if "poietics" in r["root"])


def short(root: str) -> str:
    parts = pathlib.PurePath(root).parts
    return "/".join(parts[-2:])


out: list[str] = []
w = out.append

w("# W3 tables — evidence usage and scratch usage\n")
w("Generated by `tables.py` from `evidence_census.json` and "
  "`scratch_census.json`. Every figure is read from those files; this "
  "document computes nothing.\n")

# ---------------------------------------------------------------- evidence
w("\n## 1. Evidence usage\n")
w("\n### 1a. P-R1, per bound document\n")
w("\nRun `1b31f0065687bd24f64bb08acae1245446b4b31c31b90b141ff95cd5759c9a97`. "
  "`cited` counts VERIFIED citations only (`EVIDENCE_CITATION_VERIFIED`); an "
  "unverified citation is recorded evidence of a failed citation, not an "
  "engaged one.\n")
w("\n| document | bytes | sections admitted | sections cited | cited | conj-side | critic-side |")
w("|---|---:|---:|---:|---:|---:|---:|")
for r in PR1["per_source"]:
    w(f"| `{r['source']}` | {r['bytes']:,} | {r['blocks_admitted']} | "
      f"{r['blocks_cited']} | {r['verified_citations']} | "
      f"{r['conjecture_side']} | {r['critic_side']} |")
d = PR1["dead_weight"]
w(f"| **total** | **{PR1['dossier']['block_bytes_total']:,}** | "
  f"**{d['blocks_admitted']}** | **{d['blocks_ever_cited']}** | "
  f"**{PR1['citations']['verified']}** | "
  f"**{PR1['citations']['verified_by_side'].get('conjecture-side', 0)}** | "
  f"**{PR1['citations']['verified_by_side'].get('critic-side', 0)}** |")

w("\n### 1b. P-R1, citations by cycle and by seat\n")
w("\n| cycle | problem selected | verified citations |")
w("|---|---|---:|")
for row in PR1["citations"]["cycles_by_problem"]:
    w(f"| {row['cycle']} | `{row['problem']}` | {row['verified_citations']} |")
w("\n| seat | verified citations |")
w("|---|---:|")
for s, n in PR1["citations"]["verified_by_seat"].items():
    w(f"| `{s}` | {n} |")
_rows = PR1["citations"]["cycles_by_problem"]
_seed = [r for r in _rows if not str(r["problem"]).startswith(("disc:", "conn:"))]
_spawn = [r for r in _rows if str(r["problem"]).startswith(("disc:", "conn:"))]
_spawn_detail = ", ".join(
    "cycle {}: {}".format(r["cycle"], r["verified_citations"]) for r in _spawn)
w(f"\nEvery one of the {len(_seed)} cycles working the SEED question cited the "
  f"dossier ({min(r['verified_citations'] for r in _seed)}-"
  f"{max(r['verified_citations'] for r in _seed)} citations each). Of the "
  f"{len(_spawn)} cycles working a spawned `disc:`/`conn:` problem, "
  f"{sum(1 for r in _spawn if r['verified_citations'])} cited it at all "
  f"({_spawn_detail}).\n")

w("\n### 1c. P-R1, the most-cited sections, and the ones shown and never cited\n")
w("\n| citations | times shown | document | section |")
w("|---:|---:|---|---|")
for b in PR1["per_section_top"][:12]:
    title = str(b["title"] or "*(untitled block)*").replace("|", "\\|")[:64]
    w(f"| {b['citations']} | {b['times_exposed']} | `{b['source']}` | {title} |")
w("\nShown to a model and never cited by anyone:\n")
w("\n| times shown | document | section |")
w("|---:|---|---|")
for b in PR1["per_section_all"]:
    if b["times_exposed"] and not b["citations"]:
        title = str(b["title"] or "*(untitled block)*").replace("|", "\\|")[:64]
        w(f"| {b['times_exposed']} | `{b['source']}` | {title} |")

w("\n### 1d. What could be cited at all\n")
e = PR1["exposure_vs_citation"]
w("")
w(f"- admitted blocks: **{e['blocks_admitted']}**")
w(f"- ever rendered into a pack: **{e['blocks_ever_exposed']}** "
  f"(the legend's cap is `maximum_blocks=32`)")
w(f"- never rendered, therefore uncitable: **{e['blocks_never_exposed']}** "
  f"= {e['admitted_bytes_never_exposed']:,} bytes of admitted text")
w(f"- rendered and cited: **{e['exposed_and_cited']}**")
w(f"- rendered and never cited: **{e['exposed_and_never_cited']}**, spending "
  f"{e['share_of_exposures_spent_on_never_cited_blocks']:.1%} of all "
  f"{e['exposures_total']} block renderings")
w(f"- citable packs cost **{e['citable_pack_rendered_bytes']:,} rendered "
  f"bytes** across {PR1['packs']['by_kind']['citable']['plans']} plans")

w("\n### 1e. Citation quality — quoted-and-byte-true versus handle-only\n")
q = PR1["citation_quality"]
w("\n| what the model actually claimed | count |")
w("|---|---:|")
for k, v in sorted(q["breakdown"].items(), key=lambda kv: -kv[1]):
    w(f"| {k} | {v} |")
w(f"| **total refs recovered from raw responses** | **"
  f"{q['claimed_refs_recovered_from_raw']}** |")
er = q["excerpt_reach"]
w(f"\n**How deep the verified quotes reach.** The legend renders each block as "
  f"an `excerpt_chars={er['legend_excerpt_chars']}` excerpt, but the checker "
  f"verifies against the full block. Of {er['verified_quotes']} verified "
  f"quotes: end position min {er['end_position_min']}, median "
  f"{er['end_position_median']}, max {er['end_position_max']}; "
  f"**{er['ending_within_the_excerpt']} end within the excerpt and "
  f"{er['reaching_beyond_the_excerpt']} reach beyond it.**\n")

w("\n### 1f. Citation and outcome — CORRELATION ONLY\n")
co = PR1["citation_and_outcome"]
w("\n| conjecturer artifacts | n | accepted | refuted | survivors | survival rate |")
w("|---|---:|---:|---:|---:|---:|")
for label, key in (("cited ≥1 verified block", "citing"),
                   ("cited nothing", "non_citing")):
    r = co[key]
    w(f"| {label} | {r['n']} | {r['accepted']} | {r['refuted']} | "
      f"{r['survivors']} | {r['survival_rate']:.1%} |")
w(f"\n{co['reading']}\n")

w("\n### 1g. The critic side\n")
cs = PR1["critic_side"]
w("")
w(f"- typed `premise-citation:` Measure events: **"
  f"{cs['typed_premise_citation_measures']}**, of which **"
  f"{cs['typed_and_verified']}** verified — confirming P-R1 residue R3")
w(f"- evidence refs the critic CLAIMED in its raw responses: **"
  f"{cs['claimed_premise_refs_in_raw']}**")
w("\n| what the critic's ref actually pointed at | count |")
w("|---|---:|")
for k, v in sorted(cs["what_the_critic_actually_referenced"].items(),
                   key=lambda kv: -kv[1]):
    w(f"| {k} | {v} |")

w("\n### 1h. Every root carrying citation events\n")
w("\n`regime` is `citable-legend` where an exposure gate exists and blocks are "
  "shown as 160-char excerpts under `EVD_` aliases, `dossier-pack-only` where "
  "source text is rendered under `SRC_` aliases with no exposure gate.\n")
w("\n| root | regime | sources | blocks | cited blocks | citation events | verified | verified quotes | reaching past 160 |")
w("|---|---|---:|---:|---:|---:|---:|---:|---:|")
for r in EV["roots"]:
    if not r.get("record_present"):
        continue
    ex, c = r["exposure_vs_citation"], r["citations"]
    rr = r["citation_quality"]["excerpt_reach"]
    w(f"| `{short(r['root'])}` | {ex['exposure_regime']} | "
      f"{r['dossier']['sources']} | {ex['blocks_admitted']} | "
      f"{ex['blocks_ever_cited']} | {c['measure_events']} | {c['verified']} | "
      f"{rr.get('verified_quotes', 0)} | "
      f"{rr.get('reaching_beyond_the_excerpt', 0)} |")

# ---------------------------------------------------------------- scratch
w("\n\n## 2. Scratch usage\n")
w("\n### 2a. The call-and-consequence table, every root with scratch events\n")
w("\n`write` counts authored notes (blocks, links, clusters); `read` counts "
  "the retrieval objects a `Scratch` event emits when the scratchpad is "
  "consulted (attention receipts, advisory contexts). `served` is notes proven "
  "to have been rendered back to a model. `attrib` is notes whose distinctive "
  "wording — absent from every earlier artifact, the problem statements and "
  "every admitted evidence block — reappears in a later artifact.\n")
w("\n| root | write | read | policy write/read | served | attrib | pack bytes | verdict |")
w("|---|---:|---:|---|---:|---:|---:|---|")
for r in sorted(SC["roots"], key=lambda x: str(x.get("root"))):
    u = r.get("used_or_decoration")
    if not u:
        continue
    p, rr = r.get("policy") or {}, r.get("render_receipts") or {}

    def n(v):
        return "—" if v is None else str(v)

    w(f"| `{short(r['root'])}` | {n(u.get('objects_authored'))} | "
      f"{n(u.get('scratch_read_events'))} | "
      f"{p.get('authoring_enabled')}/{p.get('retrieval_enabled')} | "
      f"{n(u.get('objects_served_back'))} | "
      f"{n(u.get('objects_with_ATTRIBUTABLE_reuse'))} | "
      f"{rr.get('rendered_bytes', 0):,} | {u['verdict'].split(' (')[0]} |")

w("\n### 2b. Used or decoration — the negative control\n")
rc = SC["retrieval_contrast"]
w("\n| group | roots | notes | notes with attributable reuse | rate | median note chars | mean novel shingles |")
w("|---|---:|---:|---:|---:|---:|---:|")
for label, key in (("retrieval enabled", "retrieval_enabled"),
                   ("retrieval DISABLED (negative control)",
                    "retrieval_disabled_negative_control")):
    b = rc[key]
    w(f"| {label} | {b['roots']} | {b['notes']} | {b['hits']} | "
      f"{b['rate']:.1%} | {b['median_note_chars']} | "
      f"{b['mean_novel_shingles_per_note']} |")
w(f"\nFisher exact, two-sided: **p = {rc['fisher_exact_two_sided_p']}**.\n")
w(f"\n{rc['reading']}\n")

w("\n### 2c. When the scratchpad was called, and why — P-R1 against a "
  "retrieval-enabled root\n")
for label, match in (("P-R1 (retrieval OFF)", "poietics"),
                     ("stress-triplet home-triage (retrieval ON, USED)",
                      "0a3e93d6")):
    r = next((x for x in SC["roots"] if match in str(x.get("root"))), None)
    if not r:
        continue
    w(f"\n**{label}** — `{short(r['root'])}`\n")
    when, why = r["when"], r["why"]
    w(f"\n- calls by kind: {json.dumps(when['by_call_kind'])}")
    w(f"- by cycle: {json.dumps(when['by_cycle'])}")
    w(f"- by seat: {json.dumps(when['by_seat'])}")
    w(f"- what preceded the first call of each burst: "
      f"{json.dumps(when['first_of_burst_preceded_by'])}")
    w(f"- typed purpose fields present: "
      f"{json.dumps(why['purpose_fields_present'])}")
    w(f"- notes marked unfinished: {why['notes_marked_unfinished']}; "
      f"carrying `why_keep_this`: {why['notes_with_why_keep_this']}")
    rr = r["render_receipts"]
    w(f"- render receipts: {rr['plans']} pack plans carried scratch, "
      f"{rr['items']} scratch items, {rr['rendered_bytes']:,} rendered bytes "
      f"({json.dumps(rr['by_kind'])})")

(T / "TABLES.md").write_text("\n".join(out) + "\n")
print(f"wrote {T / 'TABLES.md'} ({len(out)} lines)")
