#!/usr/bin/env python3
"""Render EXEMPLARS.md — verbatim excerpts from the record, nothing paraphrased.

Every quote below is read out of a committed root's blobs or objects at
generation time, so the file cannot drift from what the record says.
"""
from __future__ import annotations

import json
import pathlib
import sys

T = pathlib.Path(__file__).resolve().parent
REPO = T.parents[1]
sys.path.insert(0, str(REPO / "src"))
from deepreason.harness import Harness  # noqa: E402

EV = json.loads((T / "evidence_census.json").read_text())
SC = json.loads((T / "scratch_census.json").read_text())
PR1_ROOT = REPO / "experiments/2026-08-25-poietics-program/run"
PR1 = next(r for r in EV["roots"] if "poietics" in r["root"])
PR1S = next(r for r in SC["roots"] if "poietics" in str(r.get("root")))

out: list[str] = []
w = out.append
w("# W3 exemplars — verbatim from the record\n")
w("\nGenerated by `exemplars.py`, which reads each quote out of the committed "
  "root at generation time. Nothing here is paraphrased or reconstructed.\n")

# ---------------------------------------------------------------- E1
w("\n## E1 — a byte-true citation that quotes the legend excerpt\n")
w("\nP-R1's citable legend renders each admitted block as an "
  "`excerpt_chars=160` preview, but `check_candidate_citations` verifies the "
  "quote against the block's FULL canonical text. All 70 verified quotes in "
  "the run end at or before character 160. Two, verbatim:\n")
for e in PR1["citation_quality"]["quoted_exemplars"][:4]:
    if e["block_title"] and e["quote"].strip() == str(e["block_title"]).strip():
        w(f"\n**seq {e['seq']}, seat `{e['role']}`, from `{e['source']}`** — "
          f"the quote is exactly the section heading, which is the first thing "
          f"the excerpt carries:\n")
        w(f"\n> {e['quote']}\n")
        w(f"\nblock title: `{e['block_title']}`\n")
        break
for e in PR1["citation_quality"]["quoted_exemplars"][:6]:
    if e["role"] == "argumentative_critic":
        w(f"\n**seq {e['seq']}, seat `{e['role']}`, from `{e['source']}`** — "
          f"one of the run's two verified critic-side citations:\n")
        w(f"\n> {e['quote']}\n")
        break

# ---------------------------------------------------------------- E2
w("\n## E2 — the commonest citation form: a handle, no quote\n")
w("\n146 of the 294 evidence refs recovered from P-R1's raw responses name a "
  "block and quote nothing. Such a ref still returns "
  "`EVIDENCE_CITATION_VERIFIED` — the code means the handle resolved to an "
  "admitted evidence block that was exposed to this call, not that any text "
  "was checked. A conjecturer response, verbatim:\n")
harness = Harness(PR1_ROOT, read_only=True)
for line in (PR1_ROOT / "log.jsonl").read_text(errors="replace").splitlines():
    try:
        ev = json.loads(line)
    except json.JSONDecodeError:
        continue
    llm = ev.get("llm")
    if not (isinstance(llm, dict) and llm.get("role") == "conjecturer"):
        continue
    try:
        body = json.loads(harness.blobs.get(llm["raw_ref"]))
    except Exception:  # noqa: BLE001
        continue
    for cand in body.get("candidates") or ():
        refs = cand.get("evidence_refs") or []
        if refs and all("quote" not in r for r in refs):
            w(f"\n```json\n{json.dumps({'evidence_refs': refs}, indent=2)}\n```\n")
            break
    else:
        continue
    break

# ---------------------------------------------------------------- E3
w("\n## E3 — what the critic cited instead of the dossier\n")
w("\nThe critic seat filed 45 evidence refs in its raw responses. 21 pointed "
  "at an ARTIFACT in the run, 21 at an id that resolves to neither an artifact "
  "nor a dossier block, and 3 at a dossier block. In the artifact cases the "
  "`quote` field carries the CANDIDATE'S OWN PROSE, not admitted evidence. "
  "Two, verbatim:\n")
for ex in PR1["critic_side"]["examples"][:2]:
    w(f"\n**seq {ex['seq']}, cycle {ex['cycle']}** — ref `{ex['block_ref']}` "
      f"resolves to: **{ex['resolves_to']}**\n")
    w(f"\n> {ex['quote']}\n")

# ---------------------------------------------------------------- E4
w("\n## E4 — a P-R1 scratch note, written into a store the run had switched "
  "off reading\n")
w("\nP-R1's manifest carries `control_plane_policy.scratch_authoring.enabled = "
  "true` and `scratch_policy.enabled = false`. Seventeen notes were authored; "
  "no retrieval object exists in the root. These are notes nothing could read. "
  "Three, verbatim, with their typed purpose fields:\n")
for row in PR1S["rows"][:3]:
    if row["call_kind"] != "write":
        continue
    w(f"\n**seq {row['seq']}, cycle {row['cycle']}, "
      f"seat `{row['seat_role']}/{row['seat_model']}`, "
      f"schema `{row['object_schema']}`**\n")
    w(f"\n> {row['content_head'].strip()}\n")
    for k, v in row["purpose_fields"].items():
        w(f"\n- `{k}`: {v}")
    w("")

# ---------------------------------------------------------------- E5
w("\n## E5 — a scratch note that demonstrably reached a later candidate\n")
w("\nFrom a retrieval-ENABLED root. The note was served back by all three "
  "record witnesses (a pack plan, an advisory context and an attention "
  "receipt), and wording found in no earlier artifact, no problem statement "
  "and no admitted evidence block reappears in a later conjecture.\n")
shown = 0
for r in SC["roots"]:
    if not (r.get("policy") or {}).get("retrieval_enabled"):
        continue
    for row in r.get("rows") or ():
        if (row["call_kind"] == "write" and row["served_back"]
                and row["later_artifacts_reusing_NOVEL_text"]):
            a = row["attributable_reuse"][0]
            w(f"\n**`{pathlib.PurePath(r['root']).name}` seq {row['seq']}, "
              f"cycle {row['cycle']}** — served back by "
              f"{', '.join(row['served_back'])}\n")
            w(f"\nThe note:\n")
            w(f"\n> {row['content_head'].strip()}\n")
            w(f"\nReappearing in a `{a['role']}` artifact at event "
              f"{a['artifact_seq']} ({a['shared_novel_shingles']} distinctive "
              f"8-word sequences shared), for example:\n")
            w(f"\n> …{a['example']}…\n")
            shown += 1
            break
    if shown >= 2:
        break

# ---------------------------------------------------------------- E6
w("\n## E6 — citations into a dossier that does not exist\n")
w("\n`experiments/2026-08-22-change-epoch3-second-lineage/run` (epoch-3 "
  "attempt 4) has no attached evidence at all. Its dossier, verbatim:\n")
d = json.loads((REPO / "experiments/2026-08-22-change-epoch3-second-lineage/run"
                / "evidence-dossier.json").read_text())
w(f"\n```json\n{json.dumps({k: d[k] for k in ('schema', 'creation_provenance', 'sources', 'total_byte_count') if k in d}, indent=2)}\n```\n")
w("\nEight citation checks were nevertheless recorded against it — seven "
  "conjecture-side, one critic-side, every one returning "
  "`EVIDENCE_REF_UNKNOWN_BLOCK`. The models produced citation-shaped refs "
  "with nothing to cite.\n")

(T / "EXEMPLARS.md").write_text("\n".join(out) + "\n")
print(f"wrote {T / 'EXEMPLARS.md'} ({len(out)} blocks)")
